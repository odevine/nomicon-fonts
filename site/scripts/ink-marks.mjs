// Writes src/styles/marks.css: the scanned full stop as CSS masks, so the site's controls are made of real printed dots.
// --dot-mean is the stacked shape, --dot-1 to --dot-4 are four different printed copies from four different cards.
// Run after glyphstack.export_site with: node scripts/ink-marks.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compact } from '../integrations/served-data.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const doc = JSON.parse(readFileSync(resolve(root, 'data/glyphs/period.json'), 'utf8'));

const points = (d) => d.split(/[ML]/).slice(1).map((s) => s.replace('Z', '').split(',').map(Number)).filter((p) => p.length === 2 && p.every(Number.isFinite));
const extent = (d) => {
  const p = points(d), xs = p.map((q) => q[0]), ys = p.map((q) => q[1]);
  return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
};

// every mark shares one square window, centred on the stacked dot, so the size differences between copies are kept
const mean = doc.mean['0.5'];
const m = extent(mean);
const side = Math.max(m.x1 - m.x0, m.y1 - m.y0) * 1.12;
const cx = (m.x0 + m.x1) / 2, cy = (m.y0 + m.y1) / 2;
const view = [cx - side / 2, cy - side / 2, side, side].map((v) => v.toFixed(1)).join(' ');

const uri = (d) => {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='${view}'><path d='${d}' fill-rule='evenodd'/></svg>`;
  return `url("data:image/svg+xml,${svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23').replace(/"/g, "'")}")`;
};

// the four most typical copies, each from a different card
const picks = [];
const seen = new Set();
for (const it of [...doc.instances].sort((a, z) => z.loo_iou - a.loo_iou)) {
  if (seen.has(it.card)) continue;
  seen.add(it.card);
  picks.push(it);
  if (picks.length === 4) break;
}

const lines = [`--dot-mean: ${uri(compact(mean, 0.4))};`, ...picks.map((it, i) => `--dot-${i + 1}: ${uri(compact(it.path, 0.5))}; /* ${it.id}, ${it.card} */`)];
writeFileSync(resolve(root, 'src/styles/marks.css'), `/* Generated by scripts/ink-marks.mjs from data/glyphs/period.json. Do not edit. */\n:root {\n  ${lines.join('\n  ')}\n}\n`);
console.log(`wrote src/styles/marks.css with ${lines.length} marks from ${picks.map((p) => p.card).join(', ')}`);
